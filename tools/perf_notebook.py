#!/usr/bin/env python3
"""Maintain the perf/optimization_status.md notebooks.

Subcommands:

  migrate <file> --backend <name> [--dry-run]
      One-off normalization of a notebook to the canonical form: append-only,
      oldest-first, every entry heading `## YYYY-MM-DD: <title> — VERDICT`,
      with a generated index after the preamble. Driven by the embedded
      MIGRATION_MANIFEST; fails closed on any undated heading the manifest
      does not list, and refuses to write unless the integrity gates pass
      (body-line multiset equality, heading bijection, idempotency).

  index <file> [--check]
      Regenerate (or with --check, verify) the generated index block.

  check <file> [<file> ...]
      Lint: canonical heading format, verdict vocabulary, oldest-first
      ordering, index present and fresh.

The verdict vocabulary is LANDED, KEPT, REJECTED, CANDIDATE, DEFERRED,
INCONCLUSIVE, MIXED, RECORDED (plus UNLABELED for pre-migration entries whose
verdict could not be inferred without guessing). Legacy tokens that already
appeared in headings are preserved verbatim and whitelisted, never normalized.
"""

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

VOCAB = {
    "LANDED", "KEPT", "REJECTED", "CANDIDATE", "DEFERRED",
    "INCONCLUSIVE", "MIXED", "RECORDED", "UNLABELED",
}
LEGACY = {
    "SOLVED", "VALIDATED", "FEASIBILITY", "PARTIAL", "SUPERSEDED", "BLOCKED",
    "CLOSED", "BASELINED", "FIXED", "RESOLVED", "WIP", "KEEP", "REJECT",
}
KNOWN = VOCAB | LEGACY

# H2 headings that are preamble furniture, not entries. They stay at H2 level
# at the top of the file, before the index and the first dated entry.
PREAMBLE_HEADINGS = {"Entry Template", "Required Entry Fields"}

INDEX_BEGIN = "<!-- qx:index:begin — generated by tools/perf_notebook.py; do not hand-edit -->"
INDEX_END = "<!-- qx:index:end -->"

DATE_LEAD_RE = re.compile(r"^## (\d{4}-\d{2}-\d{2})\s*(?::|—|–|-)\s*(.*)$")
DATE_PAREN_RE = re.compile(r"^## (.*?)\s*\((\d{4}-\d{2}-\d{2})(?:[/\d-]*)\)\s*(.*)$")
CANON_DATE_RE = re.compile(r"^## (\d{4}-\d{2}-\d{2}): (.+)$")


def parse_canonical(heading):
    """Parse `## YYYY-MM-DD: <title> — VERDICT[ detail]`.

    The verdict is anchored at the LAST ` — ` separator so titles containing
    em dashes parse correctly. Returns (date, title, verdict) or None.
    """
    m = CANON_DATE_RE.match(heading)
    if not m:
        return None
    parts = m.group(2).split(" — ")
    if len(parts) < 2:
        return None
    tail = parts[-1]
    token = tail.split()[0].strip("():,.") if tail.split() else ""
    if token not in KNOWN:
        return None
    return m.group(1), " — ".join(parts[:-1]), token

